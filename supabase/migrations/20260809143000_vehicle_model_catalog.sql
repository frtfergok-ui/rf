create table public.vehicle_models (
  id bigint generated by default as identity primary key,
  brand text not null check (char_length(btrim(brand)) between 1 and 60),
  model text not null check (char_length(btrim(model)) between 1 and 80),
  vehicle_type text not null check (vehicle_type in ('sedan', 'crossover', 'van')),
  express_price numeric(10,2) not null check (express_price >= 0),
  complex_price numeric(10,2) not null check (complex_price >= 0),
  detailing_price numeric(10,2) not null check (detailing_price >= 0),
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (brand, model)
);

alter table public.vehicle_models enable row level security;
revoke all on table public.vehicle_models from anon, authenticated;
grant select on table public.vehicle_models to anon, authenticated;
grant insert (brand, model, vehicle_type, express_price, complex_price, detailing_price, active, sort_order) on table public.vehicle_models to authenticated;
grant update (brand, model, vehicle_type, express_price, complex_price, detailing_price, active, sort_order, updated_at) on table public.vehicle_models to authenticated;
grant delete on table public.vehicle_models to authenticated;
grant usage, select on sequence public.vehicle_models_id_seq to authenticated;

create policy "public can view active vehicle models"
on public.vehicle_models for select
using (active or exists (
  select 1 from public.staff_users s
  where s.id = (select auth.uid()) and s.active and s.role = 'owner'
));

