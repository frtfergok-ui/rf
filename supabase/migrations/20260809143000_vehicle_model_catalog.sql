create or replace function private.booking_vehicle_price(service_id text, car_name text, vehicle_id text)
returns numeric
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (select case service_id
      when 'express' then v.express_price
      when 'complex' then v.complex_price
      when 'detailing' then v.detailing_price
      else null end
     from public.vehicle_models v
     where lower(v.brand || ' ' || v.model) = lower(btrim(car_name)) and v.active
     limit 1),
    private.booking_service_price(service_id, vehicle_id),
    0
  );
$$;

revoke all on function private.booking_vehicle_price(text, text, text) from public;

create or replace function private.enforce_booking_capacity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  settings_row public.site_settings%rowtype;
  proposed_start timestamp;
  proposed_end timestamp;
  local_now timestamp := timezone('Europe/Chisinau', now());
  free_bay integer;
begin
  if new.status not in ('new', 'confirmed') then return new; end if;
  select * into settings_row from public.site_settings where id = 1;
  new.duration_minutes := coalesce(nullif(new.duration_minutes, 90), private.booking_service_duration(new.service), 90);
  if tg_op = 'INSERT' or new.price_amount = 0 then
    new.duration_minutes := coalesce(private.booking_service_duration(new.service), new.duration_minutes);
    new.price_amount := coalesce(private.booking_vehicle_price(new.service, new.car, new.vehicle_type), 0);
  end if;
  if new.booking_date < local_now::date or new.booking_date > local_now::date + 90 then raise exception 'booking_date_out_of_range' using errcode = '22007'; end if;
  proposed_start := new.booking_date + new.booking_time;
  proposed_end := proposed_start + make_interval(mins => new.duration_minutes);
  if proposed_start <= local_now then raise exception 'booking_time_has_passed' using errcode = '22007'; end if;
  if new.booking_time < settings_row.opening_time or proposed_end > new.booking_date + settings_row.closing_time then raise exception 'outside_working_hours' using errcode = '22007'; end if;
  if exists (select 1 from public.business_closures c where c.closure_date = new.booking_date and (c.start_time is null or (proposed_start < c.closure_date + c.end_time and proposed_end > c.closure_date + c.start_time))) then raise exception 'business_closed' using errcode = '22007'; end if;
  perform pg_advisory_xact_lock(hashtext(new.booking_date::text));
  select bay into free_bay from generate_series(1, settings_row.bay_count) bay
  where not exists (select 1 from public.bookings b where b.id is distinct from new.id and b.status in ('new','confirmed') and b.booking_date = new.booking_date and b.bay_number = bay and proposed_start < b.booking_date + b.booking_time + make_interval(mins => b.duration_minutes) and proposed_end > b.booking_date + b.booking_time)
  order by bay limit 1;
  if free_bay is null then raise exception 'slot_capacity_reached' using errcode = '23505'; end if;
  new.bay_number := free_bay;
  return new;
end;
$$;

revoke all on function private.enforce_booking_capacity() from public;
